export function calculateResult(answers){
 if(!Array.isArray(answers)||answers.length!==questions.length||answers.some((a,i)=>!Number.isInteger(a)||!questions[i].options[a])) throw new Error('请完成全部题目后查看回信');
 const sums=dimensions.map(()=>0);
 questions.forEach((q,i)=>sums[q.dimension]+=q.options[answers[i]].score);
 const total=sums.reduce((a,b)=>a+b,0);
 const ka=Math.round((total+48)/96*100);
 return {ka,huang:100-ka,type:ka>=60?'ka':ka<=40?'huang':'mixed',dimensions:sums.map(n=>Math.round((n+8)/16*100))};
}
