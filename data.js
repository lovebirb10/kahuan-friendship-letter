export function calculateResult(answers){
 if(!Array.isArray(answers)||answers.length!==questions.length)throw new Error('请完成全部题目后查看回信');
 const votes={huang:0,ka:0,mixed:0}, sums=dimensions.map(()=>0);
 for(let i=0;i<questions.length;i++){
  const a=answers[i],q=questions[i];
  if(!Number.isInteger(a)||!q.options[a])throw new Error('请完成全部题目后查看回信');
  const group=q.options[a].group;votes[group]++;sums[q.dimension]+=group==='ka'?1:group==='huang'?-1:0;
 }
 const groups=['huang','ka','mixed'];
 const raw=groups.map(g=>votes[g]/questions.length*100),pct=raw.map(Math.floor);
 const order=groups.map((_,i)=>i).sort((a,b)=>(raw[b]-pct[b])-(raw[a]-pct[a]));
 for(let i=0,n=100-pct.reduce((a,b)=>a+b,0);i<n;i++)pct[order[i]]++;
 const top=Math.max(...Object.values(votes)),winners=groups.filter(g=>votes[g]===top);
 const type=winners.length===1?winners[0]:'mixed';
 const reason=winners.length>1?'tie':type==='mixed'?'mixed':'dominant';
 return {huang:pct[0],ka:pct[1],mixed:pct[2],votes,type,reason,dimensions:sums.map(n=>Math.round((n+3)/6*100))};
}
